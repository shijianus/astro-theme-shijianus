#!/usr/bin/env node
/**
 * Playwright Visual Audit v2: i18n Component Issues
 * Using correct URL format (no locale prefix)
 */

import { chromium } from 'playwright';
import path from 'node:path';
import fs from 'node:fs';

const LIVE_BASE = 'https://blog.epocanvas.com';
const SCREENSHOT_DIR = path.resolve('scripts/audit_screenshots/component-issues');

if (!fs.existsSync(SCREENSHOT_DIR)) {
  fs.mkdirSync(SCREENSHOT_DIR, { recursive: true });
}

function hasChinese(text) {
  return /[\u4e00-\u9fa5]/.test(text || '');
}

async function auditPage(page, url, locale, outPrefix) {
  console.log(`\n🔍 Auditing [${locale}]: ${url}`);
  
  try {
    await page.goto(url, { waitUntil: 'networkidle', timeout: 30000 });
  } catch (e) {
    console.log(`  ❌ Navigation error: ${e.message}`);
    return [];
  }
  await page.waitForTimeout(3000);
  
  const pageTitle = await page.title();
  console.log(`  📄 Page title: ${pageTitle?.slice(0, 80)}`);

  const issues = [];

  // ===== AUDIT 1: interactive-unit-converter =====
  const hasConverter = await page.$('.interactive-unit-converter') !== null;
  if (hasConverter) {
    await page.waitForTimeout(2000);
    
    const converterData = await page.evaluate(() => {
      const el = document.querySelector('.interactive-unit-converter');
      if (!el) return null;
      
      return {
        dataTitle: el.getAttribute('data-title') || '',
        isBound: el.dataset.unitBound,
        innerTextSnippet: el.innerText?.slice(0, 800) || '',
        htmlSnippet: el.innerHTML?.slice(0, 2000) || '',
        // Extract specific UI strings
        categoryNames: Array.from(el.querySelectorAll('.unit-cat-btn span:last-child')).map(s => s.textContent?.trim()),
        inputLabel: el.querySelector('.unit-input-label')?.textContent?.trim(),
        resetBtnText: el.querySelector('.unit-reset-btn')?.textContent?.trim(),
        formulaLabel: el.querySelector('.unit-formula-bar > span:first-child')?.textContent?.trim(),
        rateStatus: el.querySelector('.unit-live-rate-pill')?.textContent?.trim(),
        copyButtons: Array.from(el.querySelectorAll('.unit-result-copy')).map(b => b.textContent?.trim()),
        ariaLabels: {
          decBtn: el.querySelector('.unit-step-dec')?.getAttribute('aria-label'),
          incBtn: el.querySelector('.unit-step-inc')?.getAttribute('aria-label'),
          baseSelect: el.querySelector('.unit-base-select')?.getAttribute('aria-label'),
        },
        placeholder: el.querySelector('.unit-calc-input')?.getAttribute('placeholder'),
      };
    });
    
    if (converterData) {
      console.log(`  📊 Unit Converter Audit:`);
      console.log(`     data-title: "${converterData.dataTitle?.slice(0, 80)}"`);
      console.log(`     is-bound: ${converterData.isBound}`);
      
      const checkStr = (label, str) => {
        if (!str) return;
        const cn = hasChinese(str);
        console.log(`     [${label}] "${str?.slice(0, 60)}" ${cn ? '🚨 CHINESE!' : '✅'}`);
        if (cn) {
          issues.push({ component: 'interactive-unit-converter', field: label, value: str?.slice(0, 80) });
        }
      };
      
      checkStr('data-title', converterData.dataTitle);
      checkStr('input-label', converterData.inputLabel);
      checkStr('reset-btn', converterData.resetBtnText);
      checkStr('formula-label', converterData.formulaLabel);
      checkStr('rate-status', converterData.rateStatus);
      checkStr('placeholder', converterData.placeholder);
      checkStr('dec-btn aria-label', converterData.ariaLabels?.decBtn);
      checkStr('inc-btn aria-label', converterData.ariaLabels?.incBtn);
      checkStr('base-select aria-label', converterData.ariaLabels?.baseSelect);
      
      converterData.categoryNames?.forEach((name, i) => checkStr(`category-${i}`, name));
      converterData.copyButtons?.slice(0, 3).forEach((btn, i) => checkStr(`copy-btn-${i}`, btn));
    }
    
    await page.screenshot({ path: `${SCREENSHOT_DIR}/${outPrefix}-unit-converter.png` });
  } else {
    console.log(`  ℹ️ No .interactive-unit-converter found — need to scroll`);
    
    // Try scrolling to find it
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight / 3));
    await page.waitForTimeout(1500);
    const hasConverterAfterScroll = await page.$('.interactive-unit-converter') !== null;
    if (!hasConverterAfterScroll) {
      console.log(`  ℹ️ Still no converter found after scroll`);
    }
  }

  // ===== AUDIT 2: mindmap header/footer (generated by MindmapEnhancer.astro) =====
  // Need to scroll to mindmap section and wait for JS initialization
  const hasMindmap = await page.$('.mindmap-wrapper') !== null;
  if (!hasMindmap) {
    // Try to scroll through the page to find mindmap
    await page.evaluate(() => {
      const el = document.querySelector('[class*="mindmap"]');
      if (el) el.scrollIntoView({ behavior: 'auto', block: 'center' });
    });
    await page.waitForTimeout(2000);
  }
  
  const mindmapWrapper = await page.$('.mindmap-wrapper');
  if (mindmapWrapper) {
    const mindmapData = await page.evaluate(() => {
      const wrapper = document.querySelector('.mindmap-wrapper');
      if (!wrapper) return null;
      
      return {
        headerMetaText: wrapper.querySelector('.mindmap-header__meta')?.textContent?.trim(),
        hintPill: wrapper.querySelector('.mindmap-hint-pill')?.textContent?.trim(),
        footerGuide: wrapper.querySelector('.mindmap-footer__guide')?.textContent?.trim(),
        footerBrand: wrapper.querySelector('.mindmap-footer__brand')?.textContent?.trim(),
        stateTag: wrapper.querySelector('.mindmap-state-tag')?.textContent?.trim(),
        zoomInTitle: wrapper.querySelector('.mindmap-btn--zoom-in')?.getAttribute('title'),
        zoomOutTitle: wrapper.querySelector('.mindmap-btn--zoom-out')?.getAttribute('title'),
        fitTitle: wrapper.querySelector('.mindmap-btn--fit')?.getAttribute('title'),
        expandTitle: wrapper.querySelector('.mindmap-btn--expand-all')?.getAttribute('title'),
        collapseTitle: wrapper.querySelector('.mindmap-btn--collapse-all')?.getAttribute('title'),
        fullscreenTitle: wrapper.querySelector('.mindmap-btn--fullscreen')?.getAttribute('title'),
        copyTitle: wrapper.querySelector('.mindmap-btn--copy')?.getAttribute('title'),
      };
    });
    
    if (mindmapData) {
      console.log(`\n  🗺️ Mindmap Component Audit:`);
      Object.entries(mindmapData).forEach(([k, v]) => {
        if (!v) return;
        const cn = hasChinese(v);
        console.log(`     [${k}] "${v?.slice(0, 80)}" ${cn ? '🚨 CHINESE!' : '✅'}`);
        if (cn) {
          issues.push({ component: 'mindmap-header/footer', field: k, value: v?.slice(0, 80) });
        }
      });
    }
    
    await page.screenshot({ path: `${SCREENSHOT_DIR}/${outPrefix}-mindmap.png` });
  } else {
    console.log(`  ℹ️ No .mindmap-wrapper found on page`);
  }

  // ===== AUDIT 3: article-tabs button text =====
  const tabButtons = await page.$$('.article-tabs__nav .article-tabs__button');
  if (tabButtons.length > 0) {
    console.log(`\n  🗂️ Article Tabs Button Audit (${tabButtons.length} buttons found):`);
    for (const btn of tabButtons.slice(0, 10)) {
      const text = await btn.textContent();
      const cn = hasChinese(text || '');
      console.log(`     "${text?.trim()}" ${cn ? '🚨 CHINESE!' : '✅'}`);
      if (cn) {
        issues.push({ component: 'article-tabs-nav', field: 'button-text', value: text?.trim() });
      }
    }
  }
  
  // ===== AUDIT 4: Full content scan for Chinese =====
  const chineseItems = await page.evaluate((targetLocale) => {
    const article = document.querySelector('.post-content, .markdown-body, [class*="article-content"], main .content');
    if (!article) {
      // Fallback: scan all of main
      const main = document.querySelector('main, article, .post');
      if (!main) return [];
      const walker = document.createTreeWalker(main, NodeFilter.SHOW_TEXT);
      const problems = [];
      let node;
      while ((node = walker.nextNode())) {
        const text = node.textContent?.trim();
        if (text && /[\u4e00-\u9fa5]/.test(text) && text.length > 5) {
          const parentClass = (node.parentElement?.className?.toString() || '').slice(0, 40);
          problems.push({ text: text.slice(0, 80), parentClass, parentTag: node.parentElement?.tagName?.toLowerCase() });
        }
      }
      return problems.slice(0, 25);
    }
    
    const problems = [];
    const walker = document.createTreeWalker(article, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      const text = node.textContent?.trim();
      if (text && /[\u4e00-\u9fa5]/.test(text) && text.length > 5) {
        const parentClass = (node.parentElement?.className?.toString() || '').slice(0, 40);
        problems.push({ text: text.slice(0, 80), parentClass, parentTag: node.parentElement?.tagName?.toLowerCase() });
      }
    }
    return problems.slice(0, 25);
  }, locale);
  
  if (chineseItems.length > 0 && locale !== 'zh-CN' && locale !== 'zh-Hant') {
    console.log(`\n  🔴 Untranslated Chinese found in main content [${locale}]:`);
    chineseItems.forEach(item => {
      console.log(`     [${item.parentTag}.${item.parentClass}] "${item.text}"`);
      issues.push({ component: 'content-body', field: `${item.parentTag}.${item.parentClass}`, value: item.text });
    });
  } else if (chineseItems.length === 0) {
    console.log(`\n  ✅ No untranslated Chinese found in main content`);
  }
  
  // Full page screenshot
  await page.screenshot({ path: `${SCREENSHOT_DIR}/${outPrefix}-fullpage.png`, fullPage: true });
  
  return issues;
}

async function main() {
  const browser = await chromium.launch({ headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await ctx.newPage();
  
  const POST = 'content-formats-and-markup-mastery';
  
  const tests = [
    { locale: 'es', url: `${LIVE_BASE}/posts/${POST}-es/` },
    { locale: 'en', url: `${LIVE_BASE}/posts/${POST}-en/` },
    { locale: 'fr', url: `${LIVE_BASE}/posts/${POST}-fr/` },
    { locale: 'de', url: `${LIVE_BASE}/posts/${POST}-de/` },
    { locale: 'zh-CN', url: `${LIVE_BASE}/posts/${POST}/` },  // source - baseline
  ];
  
  const allIssues = {};
  
  for (const { locale, url } of tests) {
    try {
      const issues = await auditPage(page, url, locale, `v2-${locale}`);
      allIssues[locale] = issues;
    } catch (err) {
      console.error(`  ❌ Error auditing [${locale}]: ${err.message}`);
      allIssues[locale] = [{ error: err.message }];
    }
  }
  
  await browser.close();
  
  console.log('\n\n======== FINAL AUDIT SUMMARY ========');
  let totalIssues = 0;
  for (const [locale, issues] of Object.entries(allIssues)) {
    if (locale === 'zh-CN') continue; // skip source
    const relevant = issues.filter(i => !i.error);
    totalIssues += relevant.length;
    if (relevant.length > 0) {
      console.log(`\n❌ [${locale}] - ${relevant.length} issues:`);
      relevant.forEach((issue, idx) => {
        console.log(`   ${idx+1}. [${issue.component}] [${issue.field}] "${issue.value?.slice(0, 80)}"`);
      });
    } else {
      console.log(`\n✅ [${locale}] - No i18n issues detected`);
    }
  }
  
  console.log(`\n📊 Total i18n issues found: ${totalIssues}`);
  
  const reportPath = `${SCREENSHOT_DIR}/audit-report-v2.json`;
  fs.writeFileSync(reportPath, JSON.stringify({ allIssues, totalIssues }, null, 2));
  console.log(`📄 Full report: ${reportPath}`);
}

main().catch(err => {
  console.error('Fatal:', err);
  process.exit(1);
});
