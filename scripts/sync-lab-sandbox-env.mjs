import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outDir = path.join(rootDir, 'functions', 'generated');
const outFile = path.join(outDir, 'lab-env.ts');

const rawOrigin = (process.env.PUBLIC_LAB_SANDBOX_ORIGIN || '').trim();

fs.mkdirSync(outDir, { recursive: true });
const content = `// Auto-generated by scripts/sync-lab-sandbox-env.mjs during build.\nexport const BUILD_TIME_LAB_SANDBOX_ORIGIN = ${JSON.stringify(rawOrigin)};\n`;
fs.writeFileSync(outFile, content, 'utf8');
